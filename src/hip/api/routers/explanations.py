"""Model-written explanations, served as interpretation and labeled as such.

Read-only, like every other endpoint. `hip explain` generates and stores; this reads a
row back (ARCHITECTURE #6). No request path loads a model — a model load is seconds and
gigabytes, and on 16GB of unified memory a resident model would push the rest of the
platform into swap.

The response is shaped so a consumer cannot present this as a measurement by accident.
`kind` is the literal string `interpretation`, the generating model is named, and `stale`
says whether the numbers moved since the text was written. A client that ignores all
three has to do so deliberately.
"""

from __future__ import annotations

from datetime import datetime
from typing import Annotated, Literal

from fastapi import APIRouter, HTTPException, Query
from pydantic import BaseModel, Field
from sqlalchemy import select

from hip.api.deps import SessionDep
from hip.api.params import Window
from hip.packets import PacketUnavailable, build_packet, packet_hash
from hip.warehouse.models import RegionExplanation

router = APIRouter(tags=["explanations"])

DISCLAIMER = (
    "Generated by a local language model from this region's analysis packet. "
    "It is interpretation of computed metrics, not a measurement, and not advice."
)


class Explanation(BaseModel):
    """A generated narrative, with everything needed to discount it appropriately."""

    kind: Literal["interpretation"] = Field(
        default="interpretation",
        description="Never 'measurement'. This text was written by a model.",
    )
    region_id: int
    window: str
    body: str
    model_id: str
    model_label: str
    runtime: str
    generated_at: datetime
    stale: bool = Field(
        description=(
            "True when the packet has changed since this text was written, so the "
            "prose may describe numbers the warehouse no longer holds."
        )
    )
    disclaimer: str = DISCLAIMER


@router.get(
    "/regions/{region_id}/explanation",
    response_model=Explanation,
    summary="Model-written explanation for a region (interpretation, not measurement)",
)
def explanation(
    region_id: int,
    session: SessionDep,
    window: Annotated[Window, Query()] = "5y",
) -> Explanation:
    """The stored explanation for one region and window.

    404 when none has been generated. That is the ordinary state of a fresh warehouse,
    not an error condition — the platform is fully usable with no explanations at all,
    which is the SPEC requirement that the AI layer stay optional.
    """
    row = session.execute(
        select(RegionExplanation).where(
            RegionExplanation.region_id == region_id,
            RegionExplanation.window == window,
        )
    ).scalar_one_or_none()
    if row is None:
        raise HTTPException(
            status_code=404,
            detail=(
                f"no explanation for region {region_id} over window '{window}'. "
                f"Generate one with `hip explain --region {region_id}`."
            ),
        )

    # Recompute against the warehouse as it stands rather than trusting the stored hash
    # to still describe current data — that comparison is the whole reason the hash is
    # stored. Same reasoning as ARCHITECTURE #42: the durable artifact is not the answer.
    try:
        stale = packet_hash(build_packet(session, region_id, window)) != row.packet_sha256
    except PacketUnavailable:
        # The region no longer builds a packet, so staleness cannot be established.
        # False is not a claim that the text is current — the disclaimer still stands.
        stale = False

    return Explanation(
        region_id=row.region_id,
        window=row.window,
        body=row.body,
        model_id=row.model_id,
        model_label=row.model_label,
        runtime=row.runtime,
        generated_at=row.generated_at,
        stale=stale,
    )
